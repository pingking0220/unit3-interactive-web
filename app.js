function selectQuizOption(button) {
  const slide = currentSlide();
  const session = getQuizSession(slide);
  if (session.submitted) return;
  const questionIndex = Number(button.dataset.question);
  const choiceIndex = Number(button.dataset.choice);
  session.questions[questionIndex].selected = choiceIndex;
  session.feedback = "";
  renderQuiz();
}

function submitQuizRound() {
  const slide = currentSlide();
  const session = getQuizSession(slide);

  if (session.submitted) {
    state.quizSessions[slide.id] = createQuizSession(slide);
    renderQuiz();
    return;
  }

  const unanswered = session.questions.filter((question) => question.selected === null).length;
  if (unanswered > 0) {
    session.feedback = `還有 ${unanswered} 題尚未作答。先完成五題，再送出本輪答案。`;
    els.quizFeedback.textContent = session.feedback;
    return;
  }

  const correctCount = session.questions.filter((question) => question.selected === question.answer).length;
  session.submitted = true;
  session.passed = correctCount === session.questions.length;

  if (session.passed) {
    completeCurrentSlide();
    session.feedback = `精熟通過。5 題全對，已完成「${slide.title}」測驗。`;
  } else {
    const explanations = session.questions
      .filter((question) => question.selected !== question.answer)
      .slice(0, 2)
      .map((question) => `「${question.question}」${question.explain}`)
      .join(" ");
    session.feedback = `本輪答對 ${correctCount} / 5，尚未精熟。檢查錯題後，按「重新洗題再測一次」會抽新五題並重排選項。${explanations}`;
  }

  renderQuiz();
}

function createStoryState() {
  return {
    activeChapterId: null,
    runs: {}
  };
}

function getStoryState() {
  if (!state.story) state.story = createStoryState();
  return state.story;
}

function createChapterRun(chapterId) {
  const chapter = chapterGames[chapterId];
  return {
    sceneIndex: 0,
    pendingChoice: null,
    history: [],
    fragments: [],
    points: 0,
    maxPoints: 0,
    wrongCount: 0,
    partialCount: 0,
    scores: chapter.traitOrder.reduce((scores, trait) => {
      scores[trait] = 0;
      return scores;
    }, {}),
    finished: false,
    failed: false,
    failReason: "",
    grade: null,
    endingId: null
  };
}

function normalizeChapterRun(run) {
  run.points = run.points || 0;
  run.maxPoints = run.maxPoints || 0;
  run.wrongCount = run.wrongCount || 0;
  run.partialCount = run.partialCount || 0;
  run.failed = Boolean(run.failed);
  run.failReason = run.failReason || "";
  run.grade = run.grade || null;
  return run;
}

function getActiveChapter() {
  const story = getStoryState();
  return story.activeChapterId ? chapterGames[story.activeChapterId] : null;
}

function getChapterRun(chapterId = getStoryState().activeChapterId) {
  if (!chapterId) return null;
  const story = getStoryState();
  if (!story.runs[chapterId]) story.runs[chapterId] = createChapterRun(chapterId);
  return normalizeChapterRun(story.runs[chapterId]);
}

function activateChapter(chapterId) {
  const story = getStoryState();
  story.activeChapterId = chapterId;
  getChapterRun(chapterId);
  saveStoryProgress();
  renderGame();
}

function saveStoryProgress() {
  localStorage.setItem("unit3-chapter-game-state", JSON.stringify(getStoryState()));
  localStorage.setItem("unit3-chapter-game-endings", JSON.stringify(state.storyEndings));
}

function currentStoryScene() {
  const chapter = getActiveChapter();
  const run = getChapterRun();
  return chapter && run ? chapter.moments[run.sceneIndex] : null;
}

function chooseEndingId(scores, chapter) {
  return chapter.traitOrder
    .map((trait) => [trait, scores[trait] || 0])
    .sort((left, right) => {
    if (right[1] !== left[1]) return right[1] - left[1];
    return chapter.traitOrder.indexOf(left[0]) - chapter.traitOrder.indexOf(right[0]);
  })[0][0];
}

function getMasteryPercent(run) {
  return run.maxPoints ? Math.round((run.points / run.maxPoints) * 100) : 0;
}

function getMasteryGrade(run) {
  if (run.failed) {
    return {
      label: "未通過",
      title: "任務中止",
      message: "請回到知識全景圖查證關鍵概念，再重新挑戰本章。"
    };
  }

  const percent = getMasteryPercent(run);
  if (percent >= 95) {
    return {
      label: "S",
      title: "精熟通關",
      message: "你的判斷穩定又完整，能把全景圖知識用在新的情境中。"
    };
  }
  if (percent >= 85) {
    return {
      label: "A",
      title: "穩定通關",
      message: "你大多能抓住核心概念，少數細節可以再回全景圖補強。"
    };
  }
  if (percent >= 70) {
    return {
      label: "B",
      title: "基礎通關",
      message: "你已經理解主要方向，但仍有幾個判斷需要更精準。"
    };
  }
  return {
    label: "C",
    title: "再練一次",
    message: "你完成了任務，但精熟度還不穩，建議重讀全景圖後再挑戰。"
  };
}

function buildChoiceResult(choice, chapter) {
  const mastery = masteryLevels[choice.mastery] || masteryLevels.partial;
  const failGuide = choice.eliminates ? ` ${masteryFailGuides[chapter.id] || ""}` : "";
  return `${mastery.prefix} ${choice.result}${failGuide}`;
}

function applyStoryEffects(choice) {
  const run = getChapterRun();
  Object.entries(choice.effects || {}).forEach(([key, value]) => {
    run.scores[key] = (run.scores[key] || 0) + value;
  });
  if (choice.fragment && !run.fragments.includes(choice.fragment)) {
    run.fragments.push(choice.fragment);
  }
}

